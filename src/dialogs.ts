/** Подставляет имя и грамматический род героя: {чужак}, {нашёл}, {фамилия}… */
export function fmt(s: string): string {
  const c = G.pc, f = c?.gender === 'f';
  const map: Record<string, string> = {
    'чужак': f ? 'чужачка' : 'чужак', 'Чужак': f ? 'Чужачка' : 'Чужак',
    'новенький': f ? 'новенькая' : 'новенький', 'сошёл': f ? 'сошла' : 'сошёл',
    'нашёл': f ? 'нашла' : 'нашёл', 'вернул': f ? 'вернула' : 'вернул',
    'такой': f ? 'такая' : 'такой', 'один': f ? 'одна' : 'один',
    'имя': c?.first ?? '', 'фамилия': c?.last ?? '',
  };
  return s.replace(/\{([^}]+)\}/g, (m, k: string) => map[k] ?? m);
}

