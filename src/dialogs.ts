// ============================================================ знахари — народные колдуны
const HEAL_PRICE = 8, LESSON_PRICE = 30;
let healNote = '';
/** Знахарь: заговор над ранами отряда, лавка с оберегами и травами, урок народного колдовства для оккультиста. */
function wiseDialog(s: string, shop: string, o: { hello: string; heal: string; trade: string; craft: string; lesson: string; bye: string; extra?: { q: string; a: string } }): DTree {
  return { start: 'a', nodes: {
    a: { s, t: o.hello, c: [
      { t: `Пошептать над ранами отряда (${HEAL_PRICE} ш.)`, go: 'heal', if: (g) => g.money >= HEAL_PRICE },
      { t: `[Торговать] ${o.trade}`, act: `trade:${shop}` },
      ...(o.extra ? [{ t: o.extra.q, go: 'extra' }] : []),
      { t: 'Научи меня своему ремеслу.', go: 'craft', if: (g) => g.pc?.prof === 'occultist' && !g.flags.folkLesson },
      { t: 'Бывай.', go: 'bye' },
    ] },
    heal: { s, t: o.heal, go: 'healed', do: (g) => { g.money -= HEAL_PRICE; healNote = folkHeal(); } },
    healed: { s: 'nar', go: 'a', t: () => `${healNote} (−${HEAL_PRICE} ш.)` },
    craft: { s, t: o.craft, c: [
      { t: `Заплатить за урок (${LESSON_PRICE} ш.)`, go: 'lesson', if: (g) => g.money >= LESSON_PRICE },
      { t: 'Не сейчас.', go: 'a' },
    ] },
    lesson: { s, go: 'a', t: `${o.lesson} (−${LESSON_PRICE} ш. Получен 1 знак: можно постичь ещё одно заклинание — меню O.)`, do: (g) => { g.money -= LESSON_PRICE; g.flags.folkLesson = true; } },
    ...(o.extra ? { extra: { s, go: 'a', t: o.extra.a } } : {}),
    bye: { s, t: o.bye },
  } };
}

